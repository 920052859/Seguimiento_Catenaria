async function bulkMarkModal() {
  const selected = [...document.querySelectorAll('.row-sel:checked')];
  if (!selected.length) { showToast('Selecciona soportes primero', true); return; }
  // Simple prompt - mark all selected with a specific activity
  const act = prompt('Actividad a marcar (perforacion/fijacion/soporte/mensula/aislador/perfil/hilo):');
  const actIdx = ACTS.findIndex(a=>a.key===act);
  if (actIdx < 0) return;
  for (const cb of selected) {
    const s = allSoportes.find(x=>x.id===cb.dataset.id && x.via==cb.dataset.via);
    if (s) {
      const updates = applySequentialMark(s, actIdx);
      recomputePct(s);
      s.fecha_update = new Date().toISOString();
      await saveToServer(s, updates);
    }
  }
  refreshDashboard();
  showToast(`✓ ${selected.length} soportes actualizados`);
}

