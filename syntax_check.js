function laterActivityIsDone(s, index) {
  return ACTS.slice(index + 1).some(a => s[a.key] == 1);
}

function applySequentialMark(s, index) {
  const updates = {};
  for (let i = 0; i <= index; i++) {
    if (s[ACTS[i].key] != 1) {
      s[ACTS[i].key] = 1;
      updates[ACTS[i].key] = 1;
    }
  }
  return updates;
}

function recomputePct(s) {
  s.pct = Math.round(ACTS.reduce((sum,a)=>sum + a.weight*(s[a.key]||0),0)*1000)/10;
}

