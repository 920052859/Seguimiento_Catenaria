function getSoporteColor(s) {
  if (mapMode === 'tipo') {
    return s.situacion === 'Adicional' ? '#f97316' :
           s.situacion === 'Interferencia' ? '#ef4444' : '#60a5fa';
  }
  if (mapMode === 'actividad') {
    const act = document.getElementById('map-act-sel').value;
    if (s.situacion === 'Adicional') return '#f97316';
    if (s.situacion === 'Interferencia') return '#ef4444';
    return s[act] == 1 ? '#22c55e' : '#374151';
  }
  // progreso mode
  if (s.situacion === 'Adicional') return '#f97316';
  if (s.situacion === 'Interferencia') return '#ef4444';
  if (s.pct >= 100) return '#22c55e';
  if (s.pct >= 60)  return '#34d399';
  if (s.pct >= 30)  return '#f59e0b';
  if (s.pct > 0)    return '#ef4444';
  return '#374151';
}

function renderMap() {
  if (currentTab !== 'map') return;
  
  const W = canvas.offsetWidth;
  const H = 320;
  canvas.width = W;
  canvas.height = H;
  
  const src = filtered.length > 0 ? filtered : allSoportes;
  if (!src.length) return;
  
  // Sort by via then km
  const sorted = [...src].sort((a,b) => {
    if (a.via !== b.via) return a.via - b.via;
    return (a.km||0) - (b.km||0);
  });
  
  const via1 = sorted.filter(s=>s.via===1);
  const via2 = sorted.filter(s=>s.via===2);
  
  // Canvas dimensions
  ctx.clearRect(0,0,W,H);
  
  // Background - tunnel feel
  const bgGrad = ctx.createLinearGradient(0,0,0,H);
  bgGrad.addColorStop(0,'#050810');
  bgGrad.addColorStop(1,'#0a0f1e');
  ctx.fillStyle = bgGrad;
  ctx.fillRect(0,0,W,H);
  
  // Tunnel arch lines
  ctx.strokeStyle = 'rgba(30,40,70,0.8)';
  ctx.lineWidth = 1;
  for (let i=0;i<5;i++) {
    ctx.beginPath();
    ctx.arc(W/2, -50+i*30, W*0.6+i*20, 0, Math.PI);
    ctx.stroke();
  }
  
  // Calculate positions
  const kmMin = Math.min(...src.map(s=>s.km||0).filter(k=>k>0));
  const kmMax = Math.max(...src.map(s=>s.km||0).filter(k=>k>0));
  const kmRange = kmMax - kmMin || 1;
  
  const MARGIN = 60;
  const USABLE_W = (W - MARGIN*2) * mapScale;
  const VIA1_Y = H * 0.32;
  const VIA2_Y = H * 0.68;
  const WIRE_Y1 = H * 0.18;
  const WIRE_Y2 = H * 0.82;
  
  function kmToX(km) {
    return MARGIN + ((km - kmMin) / kmRange) * USABLE_W + mapOffsetX;
  }
  
  // Draw rail lines
  ctx.strokeStyle = 'rgba(100,116,139,0.4)';
  ctx.lineWidth = 2;
  ctx.beginPath(); ctx.moveTo(MARGIN+mapOffsetX, VIA1_Y+20); ctx.lineTo(MARGIN+USABLE_W+mapOffsetX, VIA1_Y+20); ctx.stroke();
  ctx.beginPath(); ctx.moveTo(MARGIN+mapOffsetX, VIA2_Y-20); ctx.lineTo(MARGIN+USABLE_W+mapOffsetX, VIA2_Y-20); ctx.stroke();
  
  // Draw via labels
  ctx.fillStyle = 'rgba(148,163,184,0.6)';
  ctx.font = 'bold 11px Segoe UI';
  ctx.textAlign = 'left';
  ctx.fillText('VIA 1', 4, VIA1_Y+4);
  ctx.fillText('VIA 2', 4, VIA2_Y+4);
  
  // Draw tramo dividers & labels
  const tramoKmMap = {
    'PV11-E12': kmMin,
    'E12-E13': 12000,
    'E13-E14': 13000,
    'E14-E15': 14000,
    'E15-E16': 15000,
    'E16-E17': 16000,
    'E17-E18': 17000,
    'E18-E19': 18000,
    'E19-PV19': 19000,
  };
  
  const stations = [
    {label:'PV11', km: kmMin},
    {label:'E12', km:12000},{label:'E13', km:13000},{label:'E14', km:14000},
    {label:'E15', km:15000},{label:'E16', km:16000},{label:'E17', km:17000},
    {label:'E18', km:18000},{label:'E19', km:19000},{label:'PV19', km:19142}
  ];
  
  stations.forEach(st => {
    const x = kmToX(st.km);
    if (x < 0 || x > W) return;
    ctx.strokeStyle = 'rgba(99,102,241,0.3)';
    ctx.lineWidth = 1;
    ctx.setLineDash([4,4]);
    ctx.beginPath(); ctx.moveTo(x,20); ctx.lineTo(x,H-20); ctx.stroke();
    ctx.setLineDash([]);
    ctx.fillStyle = 'rgba(129,140,248,0.9)';
    ctx.font = 'bold 10px Segoe UI';
    ctx.textAlign = 'center';
    ctx.fillText(st.label, x, 14);
  });
  
  // Draw catenary wire (simulated wavy line)
  function drawWire(viaY, wireY) {
    ctx.strokeStyle = 'rgba(0,198,255,0.15)';
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.moveTo(MARGIN+mapOffsetX, wireY);
    for (let x=MARGIN+mapOffsetX; x<MARGIN+USABLE_W+mapOffsetX; x+=6) {
      const wave = Math.sin((x-mapOffsetX)*0.04)*3;
      ctx.lineTo(x, wireY + wave);
    }
    ctx.stroke();
  }
  drawWire(VIA1_Y, WIRE_Y1);
  drawWire(VIA2_Y, WIRE_Y2);
  
  // Draw soportes
  const soporteRadius = Math.max(2.5, Math.min(5, USABLE_W / (src.length/2) * 0.3));
  
  function drawSoportes(list, viaY, wireY) {
    list.forEach(s => {
      if (!s.km) return;
      const x = kmToX(s.km);
      if (x < 0 || x > W) return;
      
      const color = getSoporteColor(s);
      
      // Support bracket line
      ctx.strokeStyle = color;
      ctx.lineWidth = 1;
      ctx.globalAlpha = 0.7;
      ctx.beginPath();
      ctx.moveTo(x, wireY);
      ctx.lineTo(x, viaY > H/2 ? viaY - 8 : viaY + 8);
      ctx.stroke();
      
      // Mensula (horizontal arm at wire)
      ctx.beginPath();
      ctx.moveTo(x-4, wireY);
      ctx.lineTo(x+4, wireY);
      ctx.stroke();
      
      // Soporte circle
      ctx.globalAlpha = 1;
      ctx.fillStyle = color;
      ctx.beginPath();
      ctx.arc(x, viaY > H/2 ? viaY - 10 : viaY + 10, soporteRadius, 0, Math.PI*2);
      ctx.fill();
      
      // Glow for done soportes
      if (s.pct >= 100) {
        ctx.shadowColor = color;
        ctx.shadowBlur = 6;
        ctx.beginPath();
        ctx.arc(x, viaY > H/2 ? viaY - 10 : viaY + 10, soporteRadius, 0, Math.PI*2);
        ctx.fill();
        ctx.shadowBlur = 0;
      }
      
      // Special badge
      if (s.situacion === 'Adicional') {
        ctx.fillStyle = '#f97316';
        ctx.font = 'bold 7px Segoe UI';
        ctx.textAlign = 'center';
        ctx.fillText('+', x, viaY > H/2 ? viaY-9 : viaY+11);
      }
    });
  }
  
  drawSoportes(via1, VIA1_Y, WIRE_Y1);
  drawSoportes(via2, VIA2_Y, WIRE_Y2);
  
  // Legend
  updateMapLegend();
}

