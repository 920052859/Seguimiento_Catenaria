function exportCSV() {
  const fields = ['id','via','tramo','km','tipo','situacion',...ACTS.map(a=>a.key),'pct','comentario','fecha_update','actualizado_por'];
  const header = fields.join(',');
  const rows = filtered.map(s => fields.map(f => {
    const v = s[f]===null||s[f]===undefined?'':s[f];
    return typeof v==='string' && v.includes(',') ? `"${v}"` : v;
  }).join(','));
  const csv = [header,...rows].join('\n');
  const blob = new Blob(['\uFEFF'+csv], {type:'text/csv;charset=utf-8'});
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = 'catenaria_'+new Date().toISOString().slice(0,10)+'.csv';
  a.click();
}

