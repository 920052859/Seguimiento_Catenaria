function renderGantt() {
  const container = document.getElementById('gantt-rows');
  container.innerHTML = '';
  
  TRAMO_ORDER.forEach(tramo => {
    const sops = allSoportes.filter(s=>s.tramo===tramo);
    if (!sops.length) return;
    const avg = sops.reduce((s,x)=>s+x.pct,0)/sops.length;
    const color = avg<20?'var(--red)':avg<50?'var(--yellow)':avg<80?'var(--accent)':'var(--green)';
    const pctLabel = avg>=5 ? avg.toFixed(1)+'%' : '';
    container.innerHTML += `
      <div class="gantt-row" onclick="filterByTramo('${tramo}')">
        <div class="gantt-name">${tramo}</div>
        <div class="gantt-bar-track">
          <div class="gantt-bar-fill" style="width:${avg}%;background:${color}">${pctLabel}</div>
        </div>
        <div class="gantt-pct" style="color:${color}">${avg.toFixed(1)}%</div>
        <div class="gantt-count">${sops.length}</div>
      </div>`;
  });
}

function renderCrono() {
  const container = document.getElementById('crono-rows');
  container.innerHTML = '';
  const today = new Date();
  
  CRONOGRAMA.forEach(c => {
    const sops = allSoportes.filter(s=>s.tramo===c.tramo);
    const realPct = sops.length > 0 ? sops.reduce((s,x)=>s+x.pct,0)/sops.length : 0;
    
    const ini = new Date(c.inicio);
    const fin = new Date(c.fin);
    const totalDays = (fin-ini)/(1000*86400);
    const elapsedDays = Math.max(0, Math.min(totalDays, (today-ini)/(1000*86400)));
    const planPct = totalDays > 0 ? Math.min(100, elapsedDays/totalDays*100) : 0;
    const delta = realPct - planPct;
    const deltaColor = delta >= 0 ? 'var(--green)' : 'var(--red)';
    const deltaLabel = (delta>=0?'+':'')+delta.toFixed(1)+'%';
    
    container.innerHTML += `
      <div style="display:grid;grid-template-columns:140px 1fr 80px 80px 80px;gap:8px;padding:7px 0;border-top:1px solid var(--border);font-size:.8rem;align-items:center">
        <span style="font-weight:600">${c.tramo}</span>
        <span style="color:var(--text3);font-size:.72rem">${c.inicio} → ${c.fin}</span>
        <span style="color:var(--text2)">${planPct.toFixed(1)}%</span>
        <span style="color:var(--accent)">${realPct.toFixed(1)}%</span>
        <span style="color:${deltaColor};font-weight:700">${deltaLabel}</span>
      </div>`;
  });
}

