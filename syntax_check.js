function applyFilters() {
  const via = document.getElementById('f-via').value;
  const tramo = document.getElementById('f-tramo').value;
  const estado = document.getElementById('f-estado').value;
  const search = document.getElementById('f-search').value.toLowerCase();
  
  filtered = allSoportes.filter(s => {
    if (via && String(s.via) !== via) return false;
    if (tramo && s.tramo !== tramo) return false;
    if (estado === 'sin_iniciar' && s.pct > 0) return false;
    if (estado === 'en_progreso' && (s.pct === 0 || s.pct >= 100)) return false;
    if (estado === 'completo' && s.pct < 100) return false;
    if (estado === 'adicional' && s.situacion !== 'Adicional') return false;
    if (estado === 'interferencia' && s.situacion !== 'Interferencia') return false;
    if (search && !s.id.toLowerCase().includes(search) && !s.tramo.toLowerCase().includes(search)) return false;
    return true;
  });
  
  currentPage = 1;
  renderTable();
  renderMap();
}

