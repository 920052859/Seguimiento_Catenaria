function renderKPIs() {
  const container = document.getElementById('kpi-cards');
  container.innerHTML = '';
  
  // Global card
  const total = allSoportes.length;
  const globalPct = total > 0 ? allSoportes.reduce((s,x)=>s+x.pct,0)/total : 0;
  container.innerHTML += kpiCard('Avance Global', globalPct.toFixed(1)+'%', 
    total+' soportes', '#00c6ff', 100, globalPct);
  
  // Per actividad
  ACTS.forEach(a => {
    const done = allSoportes.filter(s=>s[a.key]==1).length;
    const pct = total > 0 ? done/total*100 : 0;
    container.innerHTML += kpiCard(a.label, pct.toFixed(1)+'%',
      done+' / '+total+' · peso '+Math.round(a.weight*100)+'%',
      a.color, 100, pct, Math.round(a.weight*100)+'%');
  });
}

function kpiCard(label, value, sub, color, max, current, weight='') {
  const pct = Math.min(100, current);
  return `<div class="kpi-card" style="--c:${color}">
    <div class="kpi-label">${label}</div>
    <div class="kpi-value">${value}</div>
    <div class="kpi-sub">${sub}</div>
    <div class="kpi-bar"><div class="kpi-bar-fill" style="width:${pct}%"></div></div>
    ${weight ? '<div class="kpi-weight">Peso: '+weight+'</div>' : ''}
  </div>`;
}

