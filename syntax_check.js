function renderTable() {
  const tbody = document.getElementById('table-body');
  const total = filtered.length;
  document.getElementById('table-count').textContent = total + ' soportes';
  
  const start = (currentPage-1)*PAGE_SIZE;
  const page = filtered.slice(start, start+PAGE_SIZE);
  
  tbody.innerHTML = '';
  page.forEach(s => {
    const pctClass = s.pct===0?'pct-0':s.pct<30?'pct-low':s.pct<70?'pct-mid':'pct-high';
    const rowClass = s.situacion==='Adicional'?'row-adicional':s.situacion==='Interferencia'?'row-interferencia':s.pct>=100?'row-done':'';
    const dateStr = s.fecha_update ? new Date(s.fecha_update).toLocaleDateString('es-PE') : '';
    
    const chks = ACTS.map((a, idx) => {
      const done = s[a.key] == 1;
      const locked = done && laterActivityIsDone(s, idx);
      const style = done ? `background:${a.color}22;border-color:${a.color};color:${a.color}` : '';
      return `<td class="chk-wrap">
        <div class="act-pill ${done?'done-pill':'pending'} ${locked?'locked-pill':''}"
             style="${style}"
             onclick="toggleAct('${s.id}',${s.via},'${a.key}',this)"
             title="${locked ? a.label+' bloqueada: existe una actividad posterior completada' : a.label+' · peso '+Math.round(a.weight*100)+'%'}">
          ${locked?'🔒':done?'✓':'○'} ${a.label}
        </div>
      </td>`;
    }).join('');
    
    tbody.innerHTML += `
      <tr class="${rowClass}" data-id="${s.id}" data-via="${s.via}">
        <td><input type="checkbox" class="row-sel" data-id="${s.id}" data-via="${s.via}"></td>
        <td class="td-id">${s.id}${s.situacion!=='Normal'?`<span class="badge badge-${s.situacion.toLowerCase()}">${s.situacion}</span>`:''}</td>
        <td>${s.via}</td>
        <td style="font-size:.72rem">${s.tramo}</td>
        <td class="td-km">${s.km ? s.km.toFixed(0) : '-'}</td>
        <td style="font-size:.68rem;color:var(--text3)">${(s.tipo||'').substring(0,12)}</td>
        ${chks}
        <td class="pct-cell ${pctClass}">${s.pct}%</td>
        <td class="comment-cell"><input class="comment-input" type="text" value="${s.comentario||''}" 
            placeholder="Agregar nota..." 
            onblur="saveComment('${s.id}',${s.via},this.value)"
            title="${s.solicitud||''}"></td>
        <td style="font-size:.68rem;color:var(--text3)">${dateStr}</td>
        <td><button class="btn btn-secondary" style="padding:3px 8px;font-size:.7rem" onclick="openModal('${s.id}',${s.via})">✎</button></td>
      </tr>`;
  });
  
  renderPagination(total);
}

function renderPagination(total) {
  const pages = Math.ceil(total/PAGE_SIZE);
  document.getElementById('page-info').textContent = 
    `${(currentPage-1)*PAGE_SIZE+1}–${Math.min(currentPage*PAGE_SIZE,total)} de ${total}`;
  
  const btns = document.getElementById('page-btns');
  btns.innerHTML = '';
  let start = Math.max(1, currentPage-2);
  let end = Math.min(pages, start+4);
  for (let i=start;i<=end;i++) {
    const b = document.createElement('button');
    b.className = 'page-btn' + (i===currentPage?' active':'');
    b.textContent = i;
    b.onclick = () => { currentPage=i; renderTable(); };
    btns.appendChild(b);
  }
}

