async function loadData() {
  if (USE_LOCAL_DATA) {
    // Load from embedded JSON (generated by Python script)
    try {
      const resp = await fetch('./soportes.json');
      if (resp.ok) {
        const data = await resp.json();
        allSoportes = data.soportes;
        if (data.last_update) updateTimestamp(data.last_update);
      }
    } catch(e) {
      // Fallback: use sample data for demo
      allSoportes = generateSampleData();
    }
  } else {
    try {
      const resp = await fetch(APPS_SCRIPT_URL + '?action=all');
      const data = await resp.json();
      allSoportes = data.soportes;
      updateTimestamp(data.last_update);
    } catch(e) {
      showToast('Error cargando datos del servidor', true);
    }
  }
  
  const now = new Date().toLocaleString('es-PE', {timeZone:'America/Lima',hour12:false});
  if (USE_LOCAL_DATA) applyLocalStorage();
  if (!document.getElementById('last-ts').textContent || document.getElementById('last-ts').textContent === 'Cargando...')
    document.getElementById('last-ts').textContent = now;
}

function updateTimestamp(ts) {
  if (!ts) return;
  const d = new Date(ts);
  const s = isNaN(d) ? ts : d.toLocaleString('es-PE',{timeZone:'America/Lima',hour12:false});
  document.getElementById('last-ts').textContent = s;
}

